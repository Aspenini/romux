//! Capability matrix generated from live backend declarations, so documentation cannot
//! drift from code (`docs/format-support.md` is produced by `romux formats --markdown`).

use crate::{FormatDescriptor, Operation, Support};

fn cell(d: &FormatDescriptor, op: Operation) -> String {
    match d.get(op) {
        Some(o) => o.support.as_str().to_string(),
        None => Support::Unsupported.as_str().to_string(),
    }
}

/// Render the matrix and per-format notes as Markdown.
pub fn markdown(formats: &[FormatDescriptor], conversions: &[crate::ConversionEdge]) -> String {
    let ops = Operation::ALL;
    let mut s = String::new();
    s.push_str("# Format support matrix\n\n");
    s.push_str("<!-- Generated by `romux formats --markdown` from live backend declarations. Do not edit by hand. -->\n\n");
    s.push_str("Values: `supported` (works for every valid instance), `conditional` (works when a detectable condition holds — keys, plaintext content, codecs), `read-only`, `unsupported`.\n");
    s.push_str("A listed console does not imply that every operation works for every encrypted retail file.\n\n");
    s.push_str("| Format | Platform |");
    for op in ops {
        s.push_str(&format!(" {} |", op.as_str()));
    }
    s.push_str("\n|---|---|");
    for _ in ops {
        s.push_str("---|");
    }
    s.push('\n');
    for d in formats {
        s.push_str(&format!("| `{}` | {} |", d.id, d.platform));
        for op in ops {
            s.push_str(&format!(" {} |", cell(d, op)));
        }
        s.push('\n');
    }
    s.push_str("\n## Notes per format\n");
    for d in formats {
        s.push_str(&format!(
            "\n### `{}` — {}\n\n{}. Extensions: {}.\n\n",
            d.id,
            d.name,
            d.description,
            d.extensions.iter().map(|e| format!("`.{e}`")).collect::<Vec<_>>().join(", ")
        ));
        for o in &d.operations {
            let req = if o.requires.is_empty() {
                String::new()
            } else {
                format!(" Requires: {}.", o.requires.iter().map(|r| format!("{r:?}")).collect::<Vec<_>>().join(", "))
            };
            let note = if o.note.is_empty() { String::new() } else { format!(" — {}", o.note) };
            s.push_str(&format!("- **{}**: {}{}{}\n", o.operation, o.support.as_str(), note, req));
        }
    }
    s.push_str("\n## Conversion graph\n\n| From | To | Kind | Support | Guarantees | Note |\n|---|---|---|---|---|---|\n");
    for e in conversions {
        s.push_str(&format!(
            "| `{}` | `{}` | {:?} | {} | {} | {} |\n",
            e.from,
            e.to,
            e.kind,
            e.support.as_str(),
            e.guarantees.iter().map(|g| g.describe()).collect::<Vec<_>>().join("; "),
            e.note
        ));
    }
    s
}
